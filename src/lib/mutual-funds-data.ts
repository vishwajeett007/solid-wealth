// Helper Functions
export function getFundsByCategory(category: string): FundScheme[] {
  if (!category || category === "All") {
    return MUTUAL_FUNDS_DATA;
  }
  return MUTUAL_FUNDS_DATA.filter(
    (fund) => fund.category.toLowerCase() === category.toLowerCase()
  );
}

export function getFundBySlugOrName(identifier: string): FundScheme {
  const cleanId = decodeURIComponent(identifier).toLowerCase().trim();
  const found = MUTUAL_FUNDS_DATA.find((f) => {
    return (
      f.slug.toLowerCase() === cleanId ||
      f.id.toLowerCase() === cleanId ||
      f.name.toLowerCase() === cleanId ||
      f.fullName.toLowerCase() === cleanId ||
      f.name.toLowerCase().replace(/[^a-z0-9]/g, "") ===
        cleanId.replace(/[^a-z0-9]/g, "")
    );
  });
  return found || MUTUAL_FUNDS_DATA[0]; // fallback to Axis Innovation Fund
}

