export type RiskLevel =
  | "Low"
  | "Moderately Low"
  | "Moderate"
  | "Moderately High"
  | "High"
  | "Very High";

export interface TrailingReturnItem {
  returnPct: number | null;
  rank?: string; // e.g. "2/13"
}

export interface ReturnsPeriodRow {
  period: string; // e.g. "1 Mon", "3 Mon", "6 Mon", "1 Yr", "3 Yrs", "5 Yrs", "10 Yrs"
  category: number | null;
  fund: number | null;
  benchmark: number | null;
  fundsCount?: number | null;
  rank?: number | string | null;
}

export interface StandardPerformanceRow {
  period: string; // "1 Year", "3 Year", "5 Year", "10 Year", "Since inception"
  schemeReturn: number;
  schemeValue: number; // Value of 10,000
  benchmarkReturn: number;
  benchmarkValue: number;
  addlBenchmarkReturn: number;
  addlBenchmarkValue: number;
  categoryReturn: number;
  categoryValue: number;
}

export interface SipReturnRow {
  schemeName: string;
  y3?: { invested: number; value: number; xirr: number };
  y5?: { invested: number; value: number; xirr: number };
  y10?: { invested: number; value: number; xirr: number };
  y15?: { invested: number; value: number; xirr: number };
}

export interface FundScheme {
  id: string;
  slug: string;
  name: string;
  fullName: string;
  category: string;
  fundHouse: string;
  fundManager: string;
  benchmark: string;
  additionalBenchmark: string;
  nav: number;
  navChange: number;
  navChangePct: number;
  navDate: string;
  launchDate: string;
  inceptionDate: string;
  aumCrore: number;
  aumDate: string;
  ber: number; // Base Expense Ratio %
  ter: number; // Total Expense Ratio %
  returnSinceInception: number;
  fundStatus: string;
  minInvestment: number;
  minTopup: number;
  minSip: number;
  riskStatus: RiskLevel;
  exitLoad: string;
  investmentObjective: string;

  // Trailing returns for main table
  trailing: {
    w1: TrailingReturnItem;
    m1: TrailingReturnItem;
    m3: TrailingReturnItem;
    m6: TrailingReturnItem;
    ytd: TrailingReturnItem;
  };

  // Fund Card Data
  returnsComparison: ReturnsPeriodRow[];
  assetAllocation: {
    equity: number;
    debt: number;
    cash: number;
    international: number;
  };
  portfolioBehavior: {
    mean: number;
    sharpeRatio: number;
    alpha: number;
    beta: number;
    standardDeviation: number;
    sortino: number;
  };
  marketCapDistribution: {
    largeCap: number;
    midCap: number;
    smallCap: number;
    others: number;
  };
  yearlyPerformance: Array<{
    year: string;
    fund: number | null;
    benchmark: number;
    category?: number;
  }>;
  standardPerformance: StandardPerformanceRow[];
  sipReturns: SipReturnRow[];
}

